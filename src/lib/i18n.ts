const translations: Record<Language, TranslationMap> = {
  tr,
  en,
  ar,
}

/**
 * A proxy-based translation accessor that supports dot-notation keys.
 * Usage: t.nav.home, t.auth.login, t.common.save, etc.
 * Falls back to the key itself if not found.
 */
function createTranslationProxy(map: TranslationMap): Record<string, string> {
  return new Proxy({} as Record<string, string>, {
    get(_target, prop: string) {
      return map[prop] ?? prop
    },
  })
}

/**
 * React hook that provides translations and text direction for the current language.
 *
 * @example
 * ```tsx
 * const { t, language, dir } = useTranslation()
 * <h1>{t.auth.login}</h1>
 * <div dir={dir}>...</div>
 * ```
 */
export function useTranslation() {
  const language = useAppStore((s) => s.language)
  const t = createTranslationProxy(translations[language])
  const dir = language === 'ar' ? 'rtl' as const : 'ltr' as const
  return { t, language, dir }
}
